const fs = require('node:fs');
const path = require('node:path');
const ejs = require('ejs');

const root = path.resolve(__dirname, '..');
const viewsDir = path.join(root, 'views');
const output = path.join(root, 'src', 'templates.generated.js');
const files = [];
function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (entry.name.endsWith('.ejs')) files.push(full);
  }
}
walk(viewsDir);
files.sort();
const entries = files.map((file) => {
  const name = path.relative(viewsDir, file).replaceAll(path.sep, '/').replace(/\.ejs$/, '');
  const source = fs.readFileSync(file, 'utf8');
  const compiled = ejs.compile(source, { client: true, filename: file }).toString().replace(/^function anonymous/, 'function');
  return `  ${JSON.stringify(name)}: ${compiled}`;
});
fs.writeFileSync(output, `// Generated by scripts/compile-templates.js. Do not edit manually.\nmodule.exports = { templates: {\n${entries.join(',\n')}\n} };\n`);
console.log(`Compiled ${files.length} EJS templates to ${path.relative(root, output)}`);
